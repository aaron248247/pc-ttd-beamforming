"""Phase 4E: programmatic tables -> docs/phase4_report_tables.md (all numbers from results/phase4/*.json / *.npz)."""
from _common import RES, ROOT, np, F0, DTAU_TARGET, VALID, LENGTHS
import json
from pcttd import channels as C

z = dict(np.load(RES / "4b_res30.npz")); j = json.load(open(RES / "4b_res30.json"))
try:
    z40 = dict(np.load(RES / "4b_res40.npz")); j40 = json.load(open(RES / "4b_res40.json")); rs = json.load(open(RES / "4c_resolution.json"))
except FileNotFoundError:
    z40 = j40 = rs = None
f = z["f"]; i0 = int(np.argmin(abs(f - F0)))
B = j["bands"]
L = ["# Phase 4 tables (generated by `experiments/phase4/4e_tables.py`; do not edit by hand)", "",
     f"Target step dtau_target = {DTAU_TARGET} a/c (= dN x 3.9323, Phase 3 D0 median); f0 = {F0}; N = {LENGTHS}; production res 30, decay_tol 1e-7, common minimum run time 3500 after the source. "
     "Amplitude measures are |H| (amplitude) and dB = 20 log10 of an amplitude ratio unless stated. Increments use the local-quadratic estimator (criteria Revision 5) unless labeled central.", ""]


def tab(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows] + [""]


p = B["primary_poly_tol10"]
L += ["## 1. Channel summary (res 30, values at f0 unless stated)", ""]
rows = []
for m in range(4):
    inc = "-" if m == 0 else f"{z['inc_poly'][m - 1][i0]:.3f}"
    err = "-" if m == 0 else f"{(z['inc_poly'][m - 1][i0] / DTAU_TARGET - 1) * 100:+.2f} %"
    rows.append([m, LENGTHS[m], f"{z['tau_abs'][m][i0]:.2f}", inc, "-" if m == 0 else f"{DTAU_TARGET:.4f}", err, f"{abs(z['H'][m][i0]):.4f}", f"{z['T'][m][i0]:.4f}", f"{z['R'][m][i0]:.2e}",
                 f"{z['delta'][m]:+.4f}", f"{z['t_end'][m]:.0f}"])
L += tab(["ch", "N", "abs. delay at f0 (a/c, central)", "increment vs previous (a/c)", "target increment (a/c)", "increment error", "|H| at f0", "T at f0", "R at f0", "trim delta_m (rad)", "t_end"], rows)
L += ["Band-average adjacent increments over the primary common band (least-squares phase slope; not derivative-noise limited), and per-estimator errors:", ""]
rows = [[f"{m}->{m + 1}", f"{p['inc_fit_slope'][m]:.3f}", f"{(p['inc_fit_slope'][m] / DTAU_TARGET - 1) * 100:+.2f} %", f"{p['inc_band_mean'][m]:.3f}", f"{p['inc_band_mean_rel_err'][m] * 100:+.2f} %"] for m in range(3)]
L += tab(["pair", "fit slope (a/c)", "error vs target", "mean of local-quadratic samples", "error"], rows)

L += ["## 2. Common-band summary (all four channels simultaneously)", ""]
rows = []
for lab, key in (("primary: increments +-10% (local quadratic)", "primary_poly_tol10"), ("increments +-5% (local quadratic)", "poly_tol5"), ("increments +-25% (local quadratic)", "poly_tol25"),
                 ("pre-declared central difference +-10%", "predeclared_central_tol10"), ("central +-5%", "central_tol5"), ("central +-25%", "central_tol25")):
    b = B[key]
    rows.append([lab, f"{b['f_low']:.4f}", f"{b['f_high']:.4f}", f"{b['f_center']:.4f}", f"{b['frac_bw'] * 100:.1f} %", f"{b['amp_imbalance_db_max']:.3f} dB",
                 f"{b['inc_rel_err_max'] * 100:.1f} %", f"{b['eps_raw_max_all']:.3f}", f"{b['eps_trim_max_all']:.3f}"] if b else [lab] + ["none"] * 8)
L += tab(["rule", "f_low", "f_high", "f_center", "frac. BW", "max amp. imbalance", "max increment error", "max raw phase err (rad)", "max trimmed phase err (rad)"], rows)
L += [f"Validated domain [{VALID[0]}, {VALID[1]}]: the primary band equals the whole domain, i.e. it is domain-limited (the per-criterion masks are wider than the domain except the pre-declared central-difference increment criterion).", ""]

L += ["## 3. Per-channel errors inside the primary common band", ""]
rows = [[m, LENGTHS[m], f"{p['trim_delta'][m]:+.4f}", f"{p['eps_raw_max'][m]:.3f}", f"{p['eps_trim_max'][m]:.4f}", f"{p['eps_trim_after_linear_removal_max'][m]:.4f}",
         "-" if m == 0 else f"{p['Dtau_rel_err_max'][m] * 100:.2f} %", f"{p['Dtau_f0'][m]:.3f}", f"{p['Dtau_band_fit'][m]:.3f}"] for m in range(4)]
L += tab(["ch", "N", "trim delta_m (rad)", "max |raw phase err| (rad)", "max |trimmed phase err| (rad)", "trimmed err after removing best-fit line (rad)", "max |Dtau_m / (m dtau_t) - 1| (local quadratic)", "Dtau_m(f0) (a/c, local quadratic)", "Dtau_m band fit (a/c)"], rows)
L += [f"Amplitude |H_m|/|H_0| over the band: min {p['amp_rel_to_ch0_range'][0]:.4f}, max {p['amp_rel_to_ch0_range'][1]:.4f}; T range [{p['T_min']:.4f}, {p['T_max']:.4f}]; R max {p['R_max']:.2e}; "
      f"projection residual max {p['res_max']:.3f}; unitarity defect max {p['unitarity_defect_absmax']:.4f}; imbalance at f0 {p['amp_imbalance_db_f0']:.4f} dB; max in band {p['amp_imbalance_db_max']:.4f} dB.", ""]

L += ["## 4. Numerical diagnostics per channel (res 30, validated domain)", ""]
rows = [[f"N{N}", f"{j['t_end'][str(N)]:.0f}", f"{j['wall_s'][str(N)]:.0f}", f"[{d['T'][0]:.4f}, {d['T'][1]:.4f}]", f"{d['R_max']:.2e}", f"{d['res_max']:.3f}", f"{d['defect_absmax']:.4f}"]
        for N, d in ((int(k[1:]), v) for k, v in j["diag_valid_domain"].items())]
L += tab(["channel", "t_end", "wall s", "T range", "R max", "proj. residual max", "|unitarity defect| max"], rows)
L += [f"Monotonic absolute delay with N at every sample of the validated domain: {j['monotonic_all_samples_in_valid_domain']}.  Phase-branch check (max step of the difference between plain unwrap and MPB-referenced phase): {max(j['branch_check_max_dev_rad']):.2e} rad.",
      f"RMS difference between central-difference and local-quadratic increments, in units of the target: {[round(x, 3) for x in j['inc_noise_rms_central_minus_poly_over_target_valid']]}.", ""]

L += ["## 5. Resolution validation (res 30 vs res 40, all four channels)", ""]
if rs:
    L += tab(["check (criteria Revision 4 item 8)", "res 30", "res 40", "difference", "pass"],
             [["band-mean increment change / target (valid domain, local quadratic), per pair", "-", "-", ", ".join(f"{x * 100:+.2f} %" for x in rs["mean_increment_change_over_target_valid_domain_poly"]), rs["tests"]["mean_inc_change_le_2pct"]],
              ["primary common band edges", f"{rs['band_res30'][0]:.4f}-{rs['band_res30'][1]:.4f}", f"{rs['band_res40'][0]:.4f}-{rs['band_res40'][1]:.4f}", "-", rs["tests"]["band_edges_move_le_0p002"]],
              ["max amplitude imbalance in valid domain (dB)", f"{rs['amp_imbalance_db_max_valid'][0]:.3f}", f"{rs['amp_imbalance_db_max_valid'][1]:.3f}", f"{rs['amp_imbalance_db_max_valid'][1] - rs['amp_imbalance_db_max_valid'][0]:+.3f}", rs["tests"]["imbalance_change_le_0p1dB"]],
              ["max trimmed phase error in valid domain (rad)", f"{rs['eps_trim_max_valid'][0]:.4f}", f"{rs['eps_trim_max_valid'][1]:.4f}", f"{rs['eps_trim_max_valid'][1] - rs['eps_trim_max_valid'][0]:+.4f}", rs["tests"]["eps_trim_change_le_0p1rad"]]])
    L += [f"Trim constants (rad): res 30 {[round(x, 4) for x in rs['trim_delta_res30']]}; res 40 {[round(x, 4) for x in rs['trim_delta_res40']]}.  "
          f"Max |phase difference| of H_m/H_0 between resolutions in the valid domain: {rs['max_abs_phase_diff_rel_valid']:.4f} rad; max relative |H| difference: {rs['max_amp_rel_diff_valid']:.4f}.",
          f"t_end res 30: {rs['t_end_res30']}; res 40: {rs['t_end_res40']}.", ""]
else:
    L += ["res 40 not available.", ""]

L += ["## 6. Cascade validation (T-matrix prediction from shorter direct devices vs the direct device)", ""]
rows = []
for res_lab, jj in (("30", j), ("40", j40)):
    if jj:
        for k, v in jj["cascade"].items():
            rows.append([res_lab, k.replace("_to_", " -> "), f"{v['max_abs_phase_diff']:.4f}", f"{v['max_abs_amp_rel_diff']:.4f}", f"{v['max_abs_delay_diff_ac']:.3f}", f"{v['max_abs_S11_diff']:.4f}",
                         f"{v['max_abs_phase_diff_valid_domain']:.4f}", f"{v['max_abs_amp_rel_diff_valid_domain']:.4f}", v["accepted"]])
L += tab(["res", "prediction (pair -> target N)", "max |phase diff| (rad), band", "max rel. |S21| diff, band", "max |delay diff| (a/c, central), band", "max |S11| diff, band", "phase diff, valid domain", "amp diff, valid domain", "accepted (<=0.1 rad, <=3%)"], rows)
(ROOT / "docs" / "phase4_report_tables.md").write_text("\n".join(L))
print("tables written")
